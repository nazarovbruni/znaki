def shape_svg(kind, label, cls='hshape'):
    """Форма дорожного знака с номером зала внутри."""
    if kind == 'circle':
        body = '<circle cx="100" cy="100" r="86" fill="#fff" stroke="#d7141a" stroke-width="24"/>'
        txt = f'<text x="100" y="130" text-anchor="middle" font-size="{86 if len(label) < 2 else 70}" fill="#000">{label}</text>'
    elif kind == 'triangle':
        body = '<path d="M100 14 L190 180 L10 180 Z" fill="#fff" stroke="#d7141a" stroke-width="18" stroke-linejoin="round"/>'
        txt = f'<text x="100" y="160" text-anchor="middle" font-size="62" fill="#000">{label}</text>'
    elif kind == 'square':
        body = '<rect x="10" y="10" width="180" height="180" rx="14" fill="#000"/>'
        txt = f'<text x="100" y="128" text-anchor="middle" font-size="76" fill="#fff">{label}</text>'
    else:
        body = '<path d="M100 6 L194 100 L100 194 L6 100 Z" fill="#fff" stroke="#000" stroke-width="12" stroke-linejoin="round"/><path d="M100 46 L154 100 L100 154 L46 100 Z" fill="#d7141a"/>'
        txt = ''
    return f'<svg class="{cls}" viewBox="0 0 200 200" aria-hidden="true">{body}{txt}</svg>'
